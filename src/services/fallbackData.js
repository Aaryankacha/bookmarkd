export const getFallbackBooksForSubject = (subject) => {
  const normSubject = (subject || '').toLowerCase().trim().replace(/ /g, '_');
  if (FALLBACK_BOOKS[normSubject]) {
    return FALLBACK_BOOKS[normSubject];
  }
  // If specific subject not found, try partial key match
  const matchedKey = Object.keys(FALLBACK_BOOKS).find(k => normSubject.includes(k) || k.includes(normSubject));
  if (matchedKey) {
    return FALLBACK_BOOKS[matchedKey];
  }
  // Otherwise return general trending books as fallback
  return FALLBACK_BOOKS.trending;
};
